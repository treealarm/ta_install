using System.Text;

namespace TaVmsHost;

// Writes the Dapr components and the sidecar configuration from the merged environment, on every
// start. In Docker the components are files beside .env carrying their own copy of the passwords —
// Dapr does not expand environment variables in component metadata — and db-init compares the two
// copies. Generating them here leaves one copy, so there is nothing to compare.
//
// Everything but the connection details and initTimeout matches ta_install/init_files/dapr_components;
// the reasons for each setting are written down there.
internal static class DaprComponents
{
  // Dapr's default is 5s, and a sidecar whose component misses it exits. On a real machine, with
  // a dozen sidecars connecting to RabbitMQ in turn, the AMQP handshake has taken longer than that;
  // each such sidecar was then restarted and came up, but only after a round of failures in the log.
  private const string InitTimeout = "30s";

  public static void Write(StackConfig config)
  {
    Directory.CreateDirectory(config.ComponentsDir);
    File.WriteAllText(Path.Combine(config.ComponentsDir, "statestore.yaml"), StateStore(config));
    File.WriteAllText(Path.Combine(config.ComponentsDir, "orderpubsub.yaml"), PubSub(config));
    if (config.Role == Role.Standalone)
    {
      File.WriteAllText(config.DaprConfigPath, Configuration(config));
      return;
    }
    foreach (var app in config.Manifest.Apps)
      File.WriteAllText(config.SidecarConfigPath(app.AppId), SidecarConfiguration(app));
  }

  private const string Header =
    "# Generated by TaVmsHost from the environment on every start: edit site.env, not this file.\n";

  internal static string StateStore(StackConfig c)
  {
    var conn = string.Join(' ',
      $"host={PgValue(c.Require("POSTGRES_HOST"))}",
      $"port={c.RequirePort("POSTGRES_PORT")}",
      $"user={PgValue(c.Require("POSTGRES_USER"))}",
      $"password={PgValue(c.Require("POSTGRES_PASSWORD"))}",
      $"database={PgValue(c.Require("POSTGRES_STATE_DB"))}",
      "sslmode=disable");
    return Header + $"""
      apiVersion: dapr.io/v1alpha1
      kind: Component
      metadata:
        name: {c.Require("DAPR_STATE_STORE_NAME")}
      spec:
        type: state.postgresql
        version: v1
        initTimeout: {InitTimeout}
        metadata:
        - name: connectionString
          value: {YamlString(conn)}
        - name: actorStateStore
          value: "true"
        - name: keyPrefix
          value: "name"

      """;
  }

  internal static string PubSub(StackConfig c)
  {
    var user = Uri.EscapeDataString(c.Require("RABBITMQ_DEFAULT_USER"));
    var pass = Uri.EscapeDataString(c.Require("RABBITMQ_DEFAULT_PASS"));
    var url = $"amqp://{user}:{pass}@{c.Require("RABBITMQ_HOST")}:{c.RequirePort("RABBITMQ_PORT")}/";
    return Header + $"""
      apiVersion: dapr.io/v1alpha1
      kind: Component
      metadata:
        name: {c.Require("PUBSUB_NAME")}
      spec:
        type: pubsub.rabbitmq
        version: v1
        initTimeout: {InitTimeout}
        metadata:
        - name: connectionString
          value: {YamlString(url)}
        - name: durable
          value: "true"
        - name: deletedWhenUnused
          value: "false"
        - name: maxLen
          value: "10000"
        - name: ttlInSeconds
          value: "3600"

      """;
  }

  // One machine: sqlite, Dapr's resolver for every sidecar on one host, which keeps calls between
  // services on the loopback (mDNS would announce the LAN address, and lose every call when the
  // cable is pulled or the DHCP lease moves the machine).
  internal static string Configuration(StackConfig c) => Header + $"""
    apiVersion: dapr.io/v1alpha1
    kind: Configuration
    metadata:
      name: tavms
    spec:
      nameResolution:
        component: "sqlite"
        version: "v1"
        configuration:
          connectionString: {YamlString(Path.Combine(c.Data, "dapr", "nameresolution.db"))}

    """;

  // Several machines: Consul, as scripts/distributed.sh writes it for Linux. The sidecar registers
  // itself with this machine's agent, at DAPR_HOST_IP, and is found only while healthy. The health
  // check is its own: Consul's default would call the sidecar's HTTP API at its LAN address, and
  // that API stays on the loopback.
  internal static string SidecarConfiguration(DaprApp app) => Header + $"""
    apiVersion: dapr.io/v1alpha1
    kind: Configuration
    metadata:
      name: {app.AppId}
    spec:
      nameResolution:
        component: "consul"
        configuration:
          client:
            address: "127.0.0.1:8500"
          selfRegister: true
          selfDeregister: true
          useCache: true
          checks:
            - name: "Dapr Health Status"
              checkID: "daprHealth:{app.AppId}"
              interval: "5s"
              http: "http://127.0.0.1:{app.DaprHttpPort}/v1.0/healthz"

    """;

  // libpq keyword/value syntax: single-quoted, with backslash escaping ' and \.
  private static string PgValue(string value) =>
    "'" + value.Replace(@"\", @"\\").Replace("'", @"\'") + "'";

  private static string YamlString(string value)
  {
    var sb = new StringBuilder("\"");
    foreach (var ch in value)
    {
      sb.Append(ch switch
      {
        '\\' => @"\\",
        '"' => "\\\"",
        _ => ch.ToString(),
      });
    }
    return sb.Append('"').ToString();
  }
}
