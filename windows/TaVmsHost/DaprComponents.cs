using System.Text;

namespace TaVmsHost;

// Writes the Dapr components and the sidecar configuration from the merged environment, on every
// start. In Docker the components are files beside .env carrying their own copy of the passwords —
// Dapr does not expand environment variables in component metadata — and db-init compares the two
// copies. Generating them here leaves one copy, so there is nothing to compare.
//
// Everything but the connection details matches ta_install/init_files/dapr_components; the reasons
// for each setting are written down there.
internal static class DaprComponents
{
  public static void Write(StackConfig config)
  {
    Directory.CreateDirectory(config.ComponentsDir);
    File.WriteAllText(Path.Combine(config.ComponentsDir, "statestore.yaml"), StateStore(config));
    File.WriteAllText(Path.Combine(config.ComponentsDir, "orderpubsub.yaml"), PubSub(config));
    File.WriteAllText(config.DaprConfigPath, Configuration(config));
  }

  private const string Header =
    "# Generated by TaVmsHost from the environment on every start: edit site.env, not this file.\n";

  internal static string StateStore(StackConfig c)
  {
    var conn = string.Join(' ',
      $"host={PgValue(c.Require("POSTGRES_HOST"))}",
      $"port={c.RequirePort("POSTGRES_PORT")}",
      $"user={PgValue(c.Require("POSTGRES_USER"))}",
      $"password={PgValue(c.Require("POSTGRES_PASSWORD"))}",
      $"database={PgValue(c.Require("POSTGRES_STATE_DB"))}",
      "sslmode=disable");
    return Header + $"""
      apiVersion: dapr.io/v1alpha1
      kind: Component
      metadata:
        name: {c.Require("DAPR_STATE_STORE_NAME")}
      spec:
        type: state.postgresql
        version: v1
        metadata:
        - name: connectionString
          value: {YamlString(conn)}
        - name: actorStateStore
          value: "true"
        - name: keyPrefix
          value: "name"

      """;
  }

  internal static string PubSub(StackConfig c)
  {
    var user = Uri.EscapeDataString(c.Require("RABBITMQ_DEFAULT_USER"));
    var pass = Uri.EscapeDataString(c.Require("RABBITMQ_DEFAULT_PASS"));
    var url = $"amqp://{user}:{pass}@{c.Require("RABBITMQ_HOST")}:{c.RequirePort("RABBITMQ_PORT")}/";
    return Header + $"""
      apiVersion: dapr.io/v1alpha1
      kind: Component
      metadata:
        name: {c.Require("PUBSUB_NAME")}
      spec:
        type: pubsub.rabbitmq
        version: v1
        metadata:
        - name: connectionString
          value: {YamlString(url)}
        - name: durable
          value: "true"
        - name: deletedWhenUnused
          value: "false"
        - name: maxLen
          value: "10000"
        - name: ttlInSeconds
          value: "3600"

      """;
  }

  // mDNS is what Docker uses and the default. sqlite is Dapr's resolver for exactly this case —
  // every sidecar on one host — and the fallback if mDNS turns out unreliable on a Windows machine
  // (multicast and the firewall, Hyper-V adapters). Required, so the choice is always visible.
  internal static string Configuration(StackConfig c)
  {
    var resolver = c.Require("TAVMS_DAPR_NAME_RESOLUTION");
    var nameResolution = resolver switch
    {
      "mdns" => """
          nameResolution:
            component: "mdns"
        """,
      "sqlite" => $"""
          nameResolution:
            component: "sqlite"
            version: "v1"
            configuration:
              connectionString: {YamlString(Path.Combine(c.Data, "dapr", "nameresolution.db"))}
        """,
      _ => throw new InvalidOperationException(
        $"TAVMS_DAPR_NAME_RESOLUTION='{resolver}': expected 'mdns' or 'sqlite'"),
    };
    return Header + $"""
      apiVersion: dapr.io/v1alpha1
      kind: Configuration
      metadata:
        name: tavms
      spec:
      {nameResolution}

      """;
  }

  // libpq keyword/value syntax: single-quoted, with backslash escaping ' and \.
  private static string PgValue(string value) =>
    "'" + value.Replace(@"\", @"\\").Replace("'", @"\'") + "'";

  private static string YamlString(string value)
  {
    var sb = new StringBuilder("\"");
    foreach (var ch in value)
    {
      sb.Append(ch switch
      {
        '\\' => @"\\",
        '"' => "\\\"",
        _ => ch.ToString(),
      });
    }
    return sb.Append('"').ToString();
  }
}
